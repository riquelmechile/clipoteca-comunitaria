"""Normalizacion FFmpeg limitada: MP4 H.264, yuv420p, <=20 s."""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

from .probe import MediaProbe, probe_media


class NormalizeError(RuntimeError):
    """FFmpeg rechazo o no produjo un clip valido."""


@dataclass(frozen=True, slots=True)
class NormalizeResult:
    path: Path
    media: MediaProbe


def _output_dimensions(width: int, height: int) -> tuple[int, int]:
    factor = min(1.0, 1080 / min(width, height))
    out_width = max(2, int(width * factor) // 2 * 2)
    out_height = max(2, int(height * factor) // 2 * 2)
    return out_width, out_height


def normalize_media(
    source: str | Path,
    destination: str | Path,
    *,
    timeout: float = 180,
    threads: int = 2,
) -> NormalizeResult:
    input_path, output_path = Path(source), Path(destination)
    if output_path.suffix.lower() != ".mp4":
        raise ValueError("destination must be an mp4 path generated by the system")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    original = probe_media(input_path, timeout=min(timeout, 30))
    width, height = _output_dimensions(original.width, original.height)
    fps = min(max(original.fps or 30, 1), 60)
    filters = f"scale={width}:{height}:flags=lanczos,fps={fps:.6f}"
    command = [
        "ffmpeg",
        "-nostdin",
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-i",
        str(input_path),
        "-t",
        "20",
        "-map",
        "0:v:0",
        "-map",
        "0:a?",
        "-vf",
        filters,
        "-c:v",
        "libx264",
        "-pix_fmt",
        "yuv420p",
        "-preset",
        "medium",
        "-movflags",
        "+faststart",
        "-threads",
        str(threads),
        "-c:a",
        "aac",
        "-b:a",
        "128k",
        str(output_path),
    ]
    try:
        subprocess.run(
            command, capture_output=True, text=True, timeout=timeout, check=True
        )
        result = probe_media(output_path, timeout=min(timeout, 30))
    except (subprocess.SubprocessError, OSError) as exc:
        output_path.unlink(missing_ok=True)
        detail = getattr(exc, "stderr", "") or str(exc)
        raise NormalizeError(f"failed to normalize media: {detail[-500:]}") from exc
    if result.codec != "h264" or result.container != "mp4":
        output_path.unlink(missing_ok=True)
        raise NormalizeError("ffmpeg output did not satisfy h264/mp4 contract")
    if result.duration_seconds > 20.05:
        output_path.unlink(missing_ok=True)
        raise NormalizeError("ffmpeg output exceeds the 20 second limit")
    return NormalizeResult(output_path, result)
