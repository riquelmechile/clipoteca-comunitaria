"""Conservative FFmpeg normalization: <=20 s, H.264, yuv420p, square pixels."""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from fractions import Fraction
from pathlib import Path

from .process_env import safe_media_env
from .probe import MediaProbe, probe_media


class NormalizeError(RuntimeError):
    """FFmpeg did not produce a valid normalized clip."""


@dataclass(frozen=True, slots=True)
class NormalizeResult:
    path: Path
    media: MediaProbe


def _output_dimensions(width: int, height: int) -> tuple[int, int]:
    factor = min(1.0, 1080 / min(width, height))
    return max(2, int(width * factor) // 2 * 2), max(2, int(height * factor) // 2 * 2)


def normalize_media(
    source: str | Path,
    destination: str | Path,
    *,
    timeout: float = 180,
    threads: int = 2,
    max_duration_seconds: float = 20,
    start_seconds: float = 0,
) -> NormalizeResult:
    if not 0 < max_duration_seconds <= 20:
        raise ValueError("max_duration_seconds must be in (0, 20]")
    if not 0 <= start_seconds < float("inf"):
        raise ValueError("start_seconds must be finite and nonnegative")
    input_path, output_path = Path(source), Path(destination)
    if input_path.resolve() == output_path.resolve():
        raise ValueError("source and destination must be different files")
    if output_path.suffix.lower() != ".mp4":
        raise ValueError("destination must be an mp4 path generated by the system")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    original = probe_media(input_path, timeout=min(timeout, 30))
    if start_seconds >= original.duration_seconds:
        raise ValueError("start_seconds is outside source duration")
    width, height = _output_dimensions(original.display_width, original.display_height)
    fps_input = Fraction(original.fps_fraction)
    fps = min(max(fps_input, Fraction(1)), Fraction(60))
    fps_arg = f"{fps.numerator}/{fps.denominator}"
    filters = f"scale={width}:{height}:flags=lanczos,setsar=1,fps={fps_arg}"
    command = [
        "ffmpeg",
        "-nostdin",
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-ss",
        f"{start_seconds:.6f}",
        "-i",
        str(input_path),
        "-t",
        str(max_duration_seconds),
        "-map",
        "0:v:0",
        "-map",
        "0:a?",
        "-vf",
        filters,
        "-c:v",
        "libx264",
        "-pix_fmt",
        "yuv420p",
        "-preset",
        "medium",
        "-movflags",
        "+faststart",
        "-threads",
        str(threads),
        "-c:a",
        "aac",
        "-b:a",
        "128k",
        str(output_path),
    ]
    try:
        subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=True,
            env=safe_media_env(),
        )
        result = probe_media(output_path, timeout=min(timeout, 30))
    except (subprocess.SubprocessError, OSError) as exc:
        output_path.unlink(missing_ok=True)
        detail = getattr(exc, "stderr", "") or str(exc)
        raise NormalizeError(f"failed to normalize media: {detail[-500:]}") from exc
    if (
        result.codec != "h264"
        or result.pix_fmt != "yuv420p"
        or result.container != "mp4"
        or result.width % 2
        or result.height % 2
        or result.fps > 60
        or result.duration_seconds > max_duration_seconds
    ):
        output_path.unlink(missing_ok=True)
        raise NormalizeError("ffmpeg output violated media schema constraints")
    return NormalizeResult(output_path, result)
